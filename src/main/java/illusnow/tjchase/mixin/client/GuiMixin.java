package illusnow.tjchase.mixin.client;

import com.llamalad7.mixinextras.injector.wrapmethod.WrapMethod;
import com.llamalad7.mixinextras.injector.wrapoperation.Operation;
import illusnow.tjchase.entity.gameplay.TyingHelper;
import net.minecraft.client.Minecraft;
import net.minecraft.client.gui.Gui;
import net.minecraft.world.entity.player.Player;
import org.spongepowered.asm.mixin.Mixin;

@Mixin(Gui.class)
public class GuiMixin {
    @WrapMethod(method = "getCameraPlayer")
    private Player findTiedPlayer(Operation<Player> original) {
        Player player = Minecraft.getInstance().player;
        if (player != null && TyingHelper.getTiedTo(player) != null) {
            return player;
        }
        return original.call();
    }
}
